function pairKey(a: string, b: string): string {
  return a < b ? `${a}|${b}` : `${b}|${a}`;
}

/**
 * Counts exact hardware requirements (L-brackets + brace gussets + T-nut fastener sets)
 * from frame topology, distinguishing orthogonal joints and diagonal brace attachments.
 */
export function countFrameBrackets(model: FrameModel): {
  bracketCount: number;
  fastenerSetCount: number;
} {
  const nodeMap = new Map(model.nodes.map((n) => [n.id, n]));
  const orthoDirsByNode = new Map<string, { x: number; y: number; z: number }[]>();
  let braceCount = 0;

  for (const m of model.members) {
    if (m.isBrace) {
      braceCount++;
      continue;
    }
    const n1 = nodeMap.get(m.startNodeId);
    const n2 = nodeMap.get(m.endNodeId);
    if (!n1 || !n2) continue;
    const dx = n2.position.x - n1.position.x;
    const dy = n2.position.y - n1.position.y;
    const dz = n2.position.z - n1.position.z;
    const l = Math.hypot(dx, dy, dz);
    if (l < 1e-4) continue;
    const u = { x: dx / l, y: dy / l, z: dz / l };

    const l1 = orthoDirsByNode.get(n1.id) ?? [];
    l1.push(u);
    orthoDirsByNode.set(n1.id, l1);

    const l2 = orthoDirsByNode.get(n2.id) ?? [];
    l2.push({ x: -u.x, y: -u.y, z: -u.z });
    orthoDirsByNode.set(n2.id, l2);
  }

  let orthogonalBrackets = 0;
  for (const n of model.nodes) {
    const dirs = orthoDirsByNode.get(n.id) ?? [];
    if (dirs.length < 2) continue;
    // Skip straight-through collinear T-slot attachment points (2 opposite collinear segments)
    if (dirs.length === 2) {
      const dotVal = Math.abs(
        dirs[0].x * dirs[1].x + dirs[0].y * dirs[1].y + dirs[0].z * dirs[1].z,
      );
      if (dotVal > 0.96) continue;
    }
    orthogonalBrackets += Math.max(1, dirs.length - 1);
  }

  // Each diagonal brace adds 2 specialized end connectors (45° bevel blocks or swivel hinges)
  const bracketCount = orthogonalBrackets + braceCount * 2;
  const fastenerSetCount = bracketCount * 2;
  return { bracketCount, fastenerSetCount };
}

/**
 * If the user fixed only a partial skeleton (e.g. locked floating top rails or beams with no ground supports),
 * automatically completes grounded columns, lower tie rails, and cross-ties around the locked members
 * without ever modifying any locked member's coordinates or profile.
 */
export function autoCompleteSupportSkeleton(
  inputModel: FrameModel,
  defaultProfile: ProfileId = '2020',
): { model: FrameModel; autoGeneratedCount: number } {
  const model = cloneFrameModel(inputModel);
  const existingPairs = new Set(model.members.map((m) => pairKey(m.startNodeId, m.endNodeId)));

  // Check if the frame already has at least 2 ground/fixed supports AND every member connects to them
  const supportedNodes = model.nodes.filter((n) => n.support !== 'free');
  const nodeMap = new Map(model.nodes.map((n) => [n.id, n]));

  // Find connected components via BFS
  const adj = new Map<string, Set<string>>();
  for (const n of model.nodes) adj.set(n.id, new Set());
  for (const m of model.members) {
    adj.get(m.startNodeId)?.add(m.endNodeId);
    adj.get(m.endNodeId)?.add(m.startNodeId);
  }

  const groundedSet = new Set<string>();
  const queue = supportedNodes.map((n) => n.id);
  for (const id of queue) groundedSet.add(id);
  while (queue.length > 0) {
    const curr = queue.shift()!;
    for (const nxt of adj.get(curr) ?? []) {
      if (!groundedSet.has(nxt)) {
        groundedSet.add(nxt);
        queue.push(nxt);
      }
    }
  }

  const ungroundedElevated = model.nodes.filter(
    (n) => !groundedSet.has(n.id) && n.position.y > 40,
  );
  if (ungroundedElevated.length === 0 && supportedNodes.length >= 2) {
    return { model, autoGeneratedCount: 0 };
  }

  let autoGeneratedCount = 0;
  let nextNodeIdx = model.nodes.length + 1;
  let nextMemIdx = model.members.length + 1;

  const ensureNode = (x: number, y: number, z: number, support: FrameNode['support']): FrameNode => {
    const found = model.nodes.find(
      (n) =>
        Math.abs(n.position.x - x) < 15 &&
        Math.abs(n.position.y - y) < 15 &&
        Math.abs(n.position.z - z) < 15,
    );
    if (found) {
      if (support !== 'free' && found.support === 'free') found.support = support;
      return found;
    }
    const created: FrameNode = {
      id: `N_AUTO_${nextNodeIdx++}`,
      position: { x: Math.round(x), y: Math.round(y), z: Math.round(z) },
      support,
      load: { fx: 0, fy: 0, fz: 0 },
    };
    model.nodes.push(created);
    nodeMap.set(created.id, created);
    return created;
  };

  const addMember = (aId: string, bId: string, profileId: ProfileId, label: string) => {
    if (aId === bId) return;
    const k = pairKey(aId, bId);
    if (existingPairs.has(k)) return;
    existingPairs.add(k);
    model.members.push({
      id: `M_AUTO_${nextMemIdx++}`,
      startNodeId: aId,
      endNodeId: bId,
      profileId,
      locked: false,
      label,
    });
    autoGeneratedCount++;
  };

  // Pick corner/endpoint elevated nodes that need legs to floor (y = 0)
  const targetNodes =
    ungroundedElevated.length > 0
      ? ungroundedElevated
      : model.nodes.filter((n) => n.position.y > 40);

  // Deduplicate by (x, z) footprint, keeping highest Y at each footprint
  const footprintTop = new Map<string, FrameNode>();
  for (const n of targetNodes) {
    const key = `${Math.round(n.position.x / 20)}_${Math.round(n.position.z / 20)}`;
    const prev = footprintTop.get(key);
    if (!prev || n.position.y > prev.position.y) {
      footprintTop.set(key, n);
    }
  }

  const lowerRailNodes: FrameNode[] = [];
  for (const topN of footprintTop.values()) {
    const floorNode = ensureNode(topN.position.x, 0, topN.position.z, 'fixed');
    if (topN.position.y >= 450) {
      const midY = Math.round(topN.position.y * 0.25);
      const midNode = ensureNode(topN.position.x, midY, topN.position.z, 'free');
      addMember(floorNode.id, midNode.id, defaultProfile, '自动立柱-下');
      addMember(midNode.id, topN.id, defaultProfile, '自动立柱-上');
      lowerRailNodes.push(midNode);
    } else {
      addMember(floorNode.id, topN.id, defaultProfile, '自动支撑立柱');
    }
  }

  // Connect lower rail perimeter cleanly between adjacent columns along X or Z
  for (let i = 0; i < lowerRailNodes.length; i++) {
    for (let j = i + 1; j < lowerRailNodes.length; j++) {
      const a = lowerRailNodes[i];
      const b = lowerRailNodes[j];
      const sameX = Math.abs(a.position.x - b.position.x) < 20;
      const sameZ = Math.abs(a.position.z - b.position.z) < 20;
      const sameY = Math.abs(a.position.y - b.position.y) < 30;
      const dist = Math.hypot(a.position.x - b.position.x, a.position.z - b.position.z);
      if (sameY && (sameX || sameZ) && dist >= 180 && dist <= 1800) {
        addMember(a.id, b.id, defaultProfile, '自动下连杆');
      }
    }
  }

  return { model, autoGeneratedCount };
}

/**
 * Discovers candidate diagonal braces across coplanar frame bays without touching locked members.
 */
function findCandidateBraces(model: FrameModel): { startId: string; endId: string; lengthMm: number }[] {
  const existing = new Set<string>();
  const adjacency = new Map<string, Set<string>>();

  for (const n of model.nodes) adjacency.set(n.id, new Set());
  for (const m of model.members) {
    existing.add(pairKey(m.startNodeId, m.endNodeId));
    adjacency.get(m.startNodeId)?.add(m.endNodeId);
    adjacency.get(m.endNodeId)?.add(m.startNodeId);
  }

  const candidates: { startId: string; endId: string; lengthMm: number }[] = [];
  const seen = new Set<string>();
  const nodes = model.nodes;

  for (let i = 0; i < nodes.length; i++) {
    for (let j = i + 1; j < nodes.length; j++) {
      const a = nodes[i];
      const b = nodes[j];
      const key = pairKey(a.id, b.id);
      if (existing.has(key) || seen.has(key)) continue;

      const dx = Math.abs(a.position.x - b.position.x);
      const dy = Math.abs(a.position.y - b.position.y);
      const dz = Math.abs(a.position.z - b.position.z);
      const dist = Math.hypot(dx, dy, dz);

      const nonZeroAxes = (dx > 20 ? 1 : 0) + (dy > 20 ? 1 : 0) + (dz > 20 ? 1 : 0);
      if (nonZeroAxes !== 2 || dy < 40 || dist < 180 || dist > 1800) continue;

      const touchesSupport = a.support !== 'free' || b.support !== 'free';
      const neighA = adjacency.get(a.id);
      const neighB = adjacency.get(b.id);
      if (!neighA || !neighB) continue;

      let validBay = touchesSupport;
      if (!validBay) {
        for (const n of neighA) {
          if (neighB.has(n)) {
            validBay = true;
            break;
          }
        }
      }
      if (!validBay) {
        outer: for (const na of neighA) {
          const adjNa = adjacency.get(na);
          if (!adjNa) continue;
          for (const nb of neighB) {
            if (adjNa.has(nb)) {
              validBay = true;
              break outer;
            }
          }
        }
      }
      if (!validBay) continue;

      // Reject any candidate diagonal that crosses/passes through an existing extrusion (zero 穿模)
      const nMapCheck = new Map(nodes.map((n) => [n.id, n]));
      let collides = false;
      for (const existingMem of model.members) {
        const m1 = nMapCheck.get(existingMem.startNodeId);
        const m2 = nMapCheck.get(existingMem.endNodeId);
        if (!m1 || !m2) continue;
        if (segmentsInteriorCollide3D(a.position, b.position, m1.position, m2.position, 28)) {
          collides = true;
          break;
        }
      }
      if (collides) continue;

      seen.add(key);
      candidates.push({ startId: a.id, endId: b.id, lengthMm: dist });
    }
  }

  const nodeMap = new Map(nodes.map((n) => [n.id, n]));
  candidates.sort((c1, c2) => {
    const s1 =
      nodeMap.get(c1.startId)?.support !== 'free' || nodeMap.get(c1.endId)?.support !== 'free'
        ? 0
        : 1;
    const s2 =
      nodeMap.get(c2.startId)?.support !== 'free' || nodeMap.get(c2.endId)?.support !== 'free'
        ? 0
        : 1;
    if (s1 !== s2) return s1 - s2;
    return c1.lengthMm - c2.lengthMm;
  });

  return candidates;
}

/**
 * Inserts genuine 45° × 45° equal-leg short triangular knee braces (150–220 mm legs)
 * at unlocked 90° vertical-column / horizontal-beam corners without splitting or altering any locked member.
 */
function addStandard45KneeBraces(
  working: FrameModel,
  lockedIds: Set<string>,
  braceProfile: ProfileId,
  maxBraces: number,
  feaOpts: {
    includeGravity: boolean;
    loadMultiplier: number;
    jointType: JointType;
    lateralPushN: number;
    curveSubdivisions: number;
  },
  initialFea: FeaResult,
  targetSwayMm: number,
): { fea: FeaResult; addedCount: number } {
  let currentFea = initialFea;
  let addedCount = 0;
  let nextNodeIdx = 1;
  let nextMemIdx = 1;

  const existingNodeIds = new Set(working.nodes.map((n) => n.id));
  const existingMemIds = new Set(working.members.map((m) => m.id));
  const allocNodeId = () => {
    while (existingNodeIds.has(`N_K45_${nextNodeIdx}`)) nextNodeIdx++;
    const id = `N_K45_${nextNodeIdx++}`;
    existingNodeIds.add(id);
    return id;
  };
  const allocMemId = (prefix: string) => {
    while (existingMemIds.has(`${prefix}_${nextMemIdx}`)) nextMemIdx++;
    const id = `${prefix}_${nextMemIdx++}`;
    existingMemIds.add(id);
    return id;
  };

  // Discover candidate 90° (vertical + horizontal) unlocked corners
  type CornerCand = {
    cornerId: string;
    vertMemberId: string;
    horizMemberId: string;
    legMm: number;
    inXPlane: boolean;
  };

  const findCornerCandidates = (): CornerCand[] => {
    const nodeMap = new Map(working.nodes.map((n) => [n.id, n]));
    const byNode = new Map<string, FrameMember[]>();
    for (const m of working.members) {
      if (m.isBrace) continue;
      const l1 = byNode.get(m.startNodeId) ?? [];
      l1.push(m);
      byNode.set(m.startNodeId, l1);
      const l2 = byNode.get(m.endNodeId) ?? [];
      l2.push(m);
      byNode.set(m.endNodeId, l2);
    }

    const cands: CornerCand[] = [];
    for (const n of working.nodes) {
      const incident = byNode.get(n.id) ?? [];
      const verts: { m: FrameMember; len: number }[] = [];
      const horizs: { m: FrameMember; len: number; inX: boolean }[] = [];

      for (const m of incident) {
        if (lockedIds.has(m.id)) continue;
        const otherId = m.startNodeId === n.id ? m.endNodeId : m.startNodeId;
        const o = nodeMap.get(otherId);
        if (!o) continue;
        const dx = Math.abs(o.position.x - n.position.x);
        const dy = Math.abs(o.position.y - n.position.y);
        const dz = Math.abs(o.position.z - n.position.z);
        const length = Math.hypot(dx, dy, dz);
        if (dy > 240 && dx < 12 && dz < 12) {
          verts.push({ m, len: length });
        } else if (dy < 12 && (dx > 240 || dz > 240) && Math.min(dx, dz) < 12) {
          horizs.push({ m, len: length, inX: dx > dz });
        }
      }

      for (const v of verts) {
        for (const h of horizs) {
          const maxLeg = Math.min(v.len, h.len) - 70;
          if (maxLeg < 130) continue;
          const legMm = Math.round(Math.max(130, Math.min(210, Math.min(v.len, h.len) * 0.36)));
          if (v.len - legMm < 70 || h.len - legMm < 70) continue;
          cands.push({
            cornerId: n.id,
            vertMemberId: v.m.id,
            horizMemberId: h.m.id,
            legMm,
            inXPlane: h.inX,
          });
        }
      }
    }

    // Prioritize X-Y plane corners first (primary lateral push plane), then higher elevation corners
    const nMap = new Map(working.nodes.map((n) => [n.id, n]));
    cands.sort((a, b) => {
      if (a.inXPlane !== b.inXPlane) return a.inXPlane ? -1 : 1;
      const ya = nMap.get(a.cornerId)?.position.y ?? 0;
      const yb = nMap.get(b.cornerId)?.position.y ?? 0;
      return yb - ya;
    });
    return cands;
  };

  const splitMemberAtDistanceFromNode = (
    model: FrameModel,
    memberId: string,
    anchorNodeId: string,
    distMm: number,
  ): string | null => {
    const idx = model.members.findIndex((m) => m.id === memberId);
    if (idx < 0) return null;
    const m = model.members[idx];
    const nAnchor = model.nodes.find((n) => n.id === anchorNodeId);
    const otherId = m.startNodeId === anchorNodeId ? m.endNodeId : m.startNodeId;
    const nOther = model.nodes.find((n) => n.id === otherId);
    if (!nAnchor || !nOther) return null;

    const dx = nOther.position.x - nAnchor.position.x;
    const dy = nOther.position.y - nAnchor.position.y;
    const dz = nOther.position.z - nAnchor.position.z;
    const totalLen = Math.hypot(dx, dy, dz);
    if (totalLen <= distMm + 40) return null;

    const t = distMm / totalLen;
    const px = Math.round(nAnchor.position.x + dx * t);
    const py = Math.round(nAnchor.position.y + dy * t);
    const pz = Math.round(nAnchor.position.z + dz * t);

    // Reuse existing coincident node if one already exists within 8mm
    let splitNode = model.nodes.find(
      (n) =>
        Math.abs(n.position.x - px) < 8 &&
        Math.abs(n.position.y - py) < 8 &&
        Math.abs(n.position.z - pz) < 8,
    );
    if (!splitNode) {
      splitNode = {
        id: allocNodeId(),
        position: { x: px, y: py, z: pz },
        support: 'free',
        load: { fx: 0, fy: 0, fz: 0 },
      };
      model.nodes.push(splitNode);
    }

    // Replace member with two collinear segments preserving exact profile & coordinates
    const seg1: FrameMember = {
      id: allocMemId('M_SEG'),
      startNodeId: anchorNodeId,
      endNodeId: splitNode.id,
      profileId: m.profileId,
      locked: false,
      label: m.label,
    };
    const seg2: FrameMember = {
      id: allocMemId('M_SEG'),
      startNodeId: splitNode.id,
      endNodeId: otherId,
      profileId: m.profileId,
      locked: false,
      label: m.label,
    };
    model.members.splice(idx, 1, seg1, seg2);
    return splitNode.id;
  };

  for (let step = 0; step < maxBraces; step++) {
    if (currentFea.isStable && currentFea.maxLateralSwayMm <= targetSwayMm && addedCount >= 2) {
      break;
    }
    const cands = findCornerCandidates();
    if (cands.length === 0) break;

    let bestAppliedModel: FrameModel | null = null;
    let bestFea: FeaResult | null = null;
    let bestDrop = 0;

    const baseSway = Math.max(1e-4, currentFea.maxLateralSwayMm);
    const baseComp = Math.max(1e-4, currentFea.totalComplianceNmm);

    for (const c of cands.slice(0, 12)) {
      const trial = cloneFrameModel(working);
      const vNodeId = splitMemberAtDistanceFromNode(trial, c.vertMemberId, c.cornerId, c.legMm);
      const hNodeId = splitMemberAtDistanceFromNode(trial, c.horizMemberId, c.cornerId, c.legMm);
      if (!vNodeId || !hNodeId || vNodeId === hNodeId) continue;

      trial.members.push({
        id: allocMemId('AUTO_K45'),
        startNodeId: vNodeId,
        endNodeId: hNodeId,
        profileId: braceProfile,
        isBrace: true,
        locked: false,
        label: `45°斜切角撑 #${addedCount + 1}`,
      });

      const testFea = solveFrameFea(trial, feaOpts);
      if (!testFea.isStable) continue;

      const swayDrop = (baseSway - testFea.maxLateralSwayMm) / baseSway;
      const compDrop = (baseComp - testFea.totalComplianceNmm) / baseComp;
      const score = 0.7 * swayDrop + 0.3 * compDrop;

      if (score > bestDrop && (swayDrop > 0.03 || compDrop > 0.03)) {
        bestDrop = score;
        bestAppliedModel = trial;
        bestFea = testFea;
      }
    }

    if (!bestAppliedModel || !bestFea) break;
    working.nodes = bestAppliedModel.nodes;
    working.members = bestAppliedModel.members;
    currentFea = bestFea;
    addedCount++;
  }

  return { fea: currentFea, addedCount };
}

/**
 * Optimizes unlocked members & diagonal braces for a specific target profile:
 * strictly preserves all `member.locked === true` extrusions (positions + profiles unchanged).
 */
function buildSchemeVariant(
  baseModel: FrameModel,
  autoGeneratedCount: number,
  variant: {
    id: AutoDesignSchemeId;
    title: string;
    tagline: string;
    braceMode: 'none' | 'knee-45' | 'full-bay';
    maxBraces: number;
    targetSwayMm: number;
    targetDeflectionMm: number;
    targetSF: number;
    recommendedJointType: JointType;
    preferFewerBrackets: boolean;
    allowPruneUnlockedBraces: boolean;
  },
  opts: AutoDesignOptions,
): AutoDesignCandidate {
  const working = cloneFrameModel(baseModel);
  const lockedIds = new Set(working.members.filter((m) => m.locked).map((m) => m.id));
  const originalProfiles = new Map<string, ProfileId>(
    baseModel.members.map((m) => [m.id, m.profileId]),
  );

  const profileRankList = PROFILE_ORDER.filter((p) => opts.allowProfiles.includes(p));
  const allowed: ProfileId[] = profileRankList.length > 0 ? profileRankList : PROFILE_ORDER;

  const evalPush = opts.lateralPushN > 0 ? opts.lateralPushN : 150;
  const feaOpts = {
    includeGravity: opts.includeGravity,
    loadMultiplier: opts.loadMultiplier,
    jointType: variant.recommendedJointType,
    lateralPushN: evalPush,
    curveSubdivisions: 4,
  };

  let currentFea = solveFrameFea(working, feaOpts);
  let addedBraces = 0;

  // Optional: prune existing unlocked braces if zero-diagonal eco variant stays stable without them
  if (variant.allowPruneUnlockedBraces) {
    const unlockedBraces = working.members.filter((m) => m.isBrace && !lockedIds.has(m.id));
    for (const br of unlockedBraces) {
      const idx = working.members.findIndex((m) => m.id === br.id);
      if (idx < 0) continue;
      const [removed] = working.members.splice(idx, 1);
      const testFea = solveFrameFea(working, feaOpts);
      if (testFea.isStable) {
        currentFea = testFea;
      } else {
        working.members.splice(idx, 0, removed);
      }
    }
  }

  // Step 1: Add strategic braces matching the variant's real-world machining craft
  const braceProfile: ProfileId = allowed.includes('2020') ? '2020' : allowed[0];

  if (variant.braceMode === 'knee-45' && variant.maxBraces > 0) {
    const res45 = addStandard45KneeBraces(
      working,
      lockedIds,
      braceProfile,
      variant.maxBraces,
      feaOpts,
      currentFea,
      variant.targetSwayMm,
    );
    currentFea = res45.fea;
    addedBraces = res45.addedCount;
  }

  // Full-bay diagonal braces (explicitly paired with swivel hinges), or fallback if 45° corners were all locked
  const needFullBay =
    variant.braceMode === 'full-bay' ||
    (variant.braceMode === 'knee-45' &&
      addedBraces === 0 &&
      currentFea.maxLateralSwayMm > variant.targetSwayMm);

  if (needFullBay && variant.maxBraces > 0) {
    const remainingBudget = Math.max(0, variant.maxBraces - addedBraces);
    for (let step = 0; step < remainingBudget; step++) {
      if (
        currentFea.isStable &&
        currentFea.maxLateralSwayMm <= variant.targetSwayMm &&
        currentFea.maxVerticalDeflectionMm <= variant.targetDeflectionMm &&
        currentFea.minSafetyFactor >= variant.targetSF
      ) {
        break;
      }

      const candidates = findCandidateBraces(working);
      if (candidates.length === 0) break;

      let bestCand: { startId: string; endId: string; lengthMm: number } | null = null;
      let bestFea: FeaResult | null = null;
      let bestScore = 0;

      const baseSway = Math.max(1e-4, currentFea.maxLateralSwayMm);
      const baseDefl = Math.max(1e-4, currentFea.maxDisplacementMm);
      const baseComp = Math.max(1e-4, currentFea.totalComplianceNmm);

      for (const cand of candidates.slice(0, 44)) {
        const tmp: FrameMember = {
          id: `AUTO_BR_${variant.id}_${step + 1}`,
          startNodeId: cand.startId,
          endNodeId: cand.endId,
          profileId: braceProfile,
          isBrace: true,
          locked: false,
          label: `满跨斜撑(万向铰链) #${step + 1}`,
        };
        working.members.push(tmp);
        const testFea = solveFrameFea(working, feaOpts);
        working.members.pop();
        if (!testFea.isStable) continue;

        const swayDrop = (baseSway - testFea.maxLateralSwayMm) / baseSway;
        const deflDrop = (baseDefl - testFea.maxDisplacementMm) / baseDefl;
        const compDrop = (baseComp - testFea.totalComplianceNmm) / baseComp;
        const addedMass = (cand.lengthMm / 1000) * getProfileSpec(braceProfile).massPerMeterKg;
        const bracketPenalty = variant.preferFewerBrackets ? 1.55 : 1.0;

        const benefit = 0.48 * swayDrop + 0.27 * deflDrop + 0.25 * compDrop;
        const score = benefit / (Math.max(0.18, addedMass) * bracketPenalty);
        if (score > bestScore && (swayDrop > 0.08 || deflDrop > 0.06)) {
          bestScore = score;
          bestCand = cand;
          bestFea = testFea;
        }
      }

      if (!bestCand || !bestFea) break;
      addedBraces++;
      working.members.push({
        id: `AUTO_BR_${variant.id}_${addedBraces}`,
        startNodeId: bestCand.startId,
        endNodeId: bestCand.endId,
        profileId: braceProfile,
        isBrace: true,
        locked: false,
        label: `满跨斜撑(万向铰链) #${addedBraces}`,
      });
      currentFea = bestFea;
    }
  }

  // Helper: all collinear split sub-segments of the same continuous extrusion share one uniform profile
  const getUniformGroup = (target: FrameMember): FrameMember[] => {
    if (!target.label || target.isBrace) return [target];
    const peers = working.members.filter(
      (m) => !lockedIds.has(m.id) && !m.isBrace && m.label === target.label,
    );
    return peers.length > 0 ? peers : [target];
  };

  // Step 2: Upgrade ONLY UNLOCKED members if constraints (SF, deflection, sway) are still exceeded
  let guard = 0;
  const meetsTargets = (f: FeaResult) =>
    f.isStable &&
    f.minSafetyFactor >= variant.targetSF &&
    f.maxLateralSwayMm <= variant.targetSwayMm &&
    f.maxVerticalDeflectionMm <= variant.targetDeflectionMm;

  while (!meetsTargets(currentFea) && guard < 16) {
    guard++;
    const unlockedRanked = working.members
      .filter((m) => !lockedIds.has(m.id))
      .map((m) => {
        const r = currentFea.memberResults[m.id];
        const pIdx = allowed.indexOf(m.profileId);
        return {
          member: m,
          pIdx,
          score: r ? r.strainEnergyNmm + r.utilization * 6000 : 0,
        };
      })
      .filter((x) => x.pIdx >= 0 && x.pIdx < allowed.length - 1)
      .sort((a, b) => b.score - a.score);

    if (unlockedRanked.length === 0) break;
    const pick = unlockedRanked[0];
    const nextProfile = allowed[pick.pIdx + 1];
    for (const peer of getUniformGroup(pick.member)) {
      peer.profileId = nextProfile;
    }
    // Keep supporting unlocked vertical columns at least as wide as horizontal beams (no beam overhanging thin columns)
    const nextWidthMm = getProfileSpec(nextProfile).widthMm;
    const nMapSync = new Map(working.nodes.map((n) => [n.id, n]));
    for (const peer of getUniformGroup(pick.member)) {
      const p1 = nMapSync.get(peer.startNodeId);
      const p2 = nMapSync.get(peer.endNodeId);
      if (!p1 || !p2) continue;
      const isHoriz = Math.abs(p2.position.y - p1.position.y) < 25;
      if (!isHoriz) continue;
      for (const endId of [peer.startNodeId, peer.endNodeId]) {
        for (const col of working.members) {
          if (lockedIds.has(col.id) || col.isBrace) continue;
          if (col.startNodeId !== endId && col.endNodeId !== endId) continue;
          const c1 = nMapSync.get(col.startNodeId);
          const c2 = nMapSync.get(col.endNodeId);
          if (!c1 || !c2) continue;
          const isVert =
            Math.abs(c2.position.y - c1.position.y) >
            Math.max(Math.abs(c2.position.x - c1.position.x), Math.abs(c2.position.z - c1.position.z));
          if (!isVert) continue;
          if (getProfileSpec(col.profileId).widthMm < nextWidthMm) {
            const matchCol = allowed.find((pid) => getProfileSpec(pid).widthMm >= nextWidthMm);
            if (matchCol) {
              for (const colPeer of getUniformGroup(col)) {
                colPeer.profileId = matchCol;
              }
            }
          }
        }
      }
    }
    currentFea = solveFrameFea(working, feaOpts);
  }

  // Step 3: Lightweighting pass on UNLOCKED members only (save aluminum without violating targets)
  let improved = true;
  let pass = 0;
  while (improved && pass < 3) {
    improved = false;
    pass++;
    const visitedLabels = new Set<string>();
    const unlockedDowngrade = working.members
      .filter((m) => !lockedIds.has(m.id))
      .map((m) => {
        const r = currentFea.memberResults[m.id];
        const pIdx = allowed.indexOf(m.profileId);
        return {
          member: m,
          pIdx,
          util: r ? r.utilization : 1,
          mass: r ? r.massKg : 0,
        };
      })
      .filter((x) => x.pIdx > 0)
      .sort((a, b) => a.util - b.util || b.mass - a.mass);

    for (const cand of unlockedDowngrade) {
      const grpKey = cand.member.label && !cand.member.isBrace ? cand.member.label : cand.member.id;
      if (visitedLabels.has(grpKey)) continue;
      visitedLabels.add(grpKey);

      const group = getUniformGroup(cand.member);
      const oldP = cand.member.profileId;
      const lowerP = allowed[cand.pIdx - 1];
      if (getProfileSpec(lowerP).massPerMeterKg >= getProfileSpec(oldP).massPerMeterKg) continue;

      const prevProfiles = group.map((g) => g.profileId);
      for (const g of group) g.profileId = lowerP;
      const testFea = solveFrameFea(working, feaOpts);
      if (meetsTargets(testFea)) {
        currentFea = testFea;
        improved = true;
      } else {
        group.forEach((g, idx) => {
          g.profileId = prevProfiles[idx];
        });
      }
    }
  }

  // Final full-resolution solve
  const finalFea = solveFrameFea(working, {
    ...feaOpts,
    curveSubdivisions: 6,
  });

  const bom = optimizeCuttingStock(working, {
    stockLengthMm: 3000,
    kerfMm: 3,
    jointType: variant.recommendedJointType,
  });
  const hw = countFrameBrackets(working);
  const diagSummary = summarizeFrameDiagonalHardware(working);
  const totalCostCNY = Math.round(bom.grandTotalCostCNY);
  const stockBarsNeeded = bom.stockPlans.length;

  let resizedMemberCount = 0;
  for (const m of working.members) {
    const orig = originalProfiles.get(m.id);
    if (orig && orig !== m.profileId) resizedMemberCount++;
  }

  let assemblyMethod = '免斜切 · 外置5孔三角连接板直装';
  if (diagSummary.miter45MemberCount > 0 && diagSummary.swivelHingeMemberCount === 0) {
    assemblyMethod = `45°斜切短角撑 ×${diagSummary.miter45MemberCount} + 45°斜角码`;
  } else if (diagSummary.swivelHingeMemberCount > 0) {
    assemblyMethod = `90°平切满跨斜撑 ×${diagSummary.swivelHingeMemberCount} + 万向活动铰链 ×${diagSummary.swivelHingeCount}`;
  } else if (variant.recommendedJointType === 'semi-rigid') {
    assemblyMethod = '免斜切 · 标准直角角码直连';
  }

  const highlights: string[] = [];
  if (lockedIds.size > 0) highlights.push(`完整保留 ${lockedIds.size} 根锁定型材位置与规格`);
  if (autoGeneratedCount > 0) highlights.push(`自动补全 ${autoGeneratedCount} 根落地立柱/连杆`);
  if (diagSummary.miter45MemberCount > 0) {
    highlights.push(
      `角落加装 ${diagSummary.miter45MemberCount} 根 45° 斜切短角撑（配 45° 斜角码 ×${diagSummary.miter45BracketCount}）`,
    );
  } else if (diagSummary.swivelHingeMemberCount > 0) {
    highlights.push(
      `配置 ${diagSummary.swivelHingeMemberCount} 根满跨斜撑（90°平切 + 万向铰链 ×${diagSummary.swivelHingeCount}）`,
    );
  } else {
    highlights.push('0 根斜型材免锯斜角，外置三角板直接拧螺丝即可防晃');
  }
  if (resizedMemberCount > 0) highlights.push(`自动调整 ${resizedMemberCount} 根未锁定型材规格`);

  return {
    id: variant.id,
    title: variant.title,
    tagline: variant.tagline,
    model: working,
    fea: finalFea,
    recommendedJointType: variant.recommendedJointType,
    bracketCount: hw.bracketCount,
    fastenerSetCount: hw.fastenerSetCount,
    stockBarsNeeded,
    totalMassKg: finalFea.totalMassKg,
    totalCostCNY,
    maxSwayMm: finalFea.maxLateralSwayMm,
    maxDeflectionMm: finalFea.maxVerticalDeflectionMm,
    minSafetyFactor: finalFea.minSafetyFactor,
    addedMemberCount: autoGeneratedCount + addedBraces,
    resizedMemberCount,
    lockedMemberCount: lockedIds.size,
    score: 0, // populated below after normalizing across all 3 Pareto schemes
    highlights,
    assemblyMethod,
    miter45BraceCount: diagSummary.miter45MemberCount,
    swivelHingeCount: diagSummary.swivelHingeCount,
  };
}

/**
 * Constrained Multi-Objective Auto-Design Solver:
 * Locks user-pinned extrusions, completes any missing support paths, and generates
 * 3 distinct Pareto-optimal schemes representing 3 real-world buildable crafts:
 *   1. 免斜切省料方案 (0 diagonal extrusions, external 5-hole gusset plates)
 *   2. 45°角撑均衡方案 (standard 45° mitered short knee braces + 45° bevel blocks)
 *   3. 满跨斜撑高刚方案 (full-bay diagonal braces + swivel hinges + gusset plates)
 */
export function runConstrainedAutoDesign(
  inputModel: FrameModel,
  options: AutoDesignOptions,
): AutoDesignResult {
  const beforeModel = cloneFrameModel(inputModel);
  const evalPush = options.lateralPushN > 0 ? options.lateralPushN : 150;
  const beforeFea = solveFrameFea(beforeModel, {
    includeGravity: options.includeGravity,
    loadMultiplier: options.loadMultiplier,
    jointType: options.jointType,
    lateralPushN: evalPush,
    curveSubdivisions: 6,
  });
  const beforeHw = countFrameBrackets(beforeModel);
  const beforeBom = optimizeCuttingStock(beforeModel, {
    stockLengthMm: 3000,
    kerfMm: 3,
    jointType: options.jointType,
  });
  const beforeTotalCostCNY = Math.round(beforeBom.grandTotalCostCNY);

  const lockedMemberIds = beforeModel.members.filter((m) => m.locked).map((m) => m.id);
  const defaultProfile: ProfileId = options.allowProfiles.includes('2020')
    ? '2020'
    : options.allowProfiles[0] ?? '2020';

  // Auto-complete floor supports if user only fixed floating/partial extrusions
  const { model: completedBase, autoGeneratedCount } = autoCompleteSupportSkeleton(
    beforeModel,
    defaultProfile,
  );

  // Build 3 complementary, physically buildable Pareto-optimal schemes
  const ecoScheme = buildSchemeVariant(
    completedBase,
    autoGeneratedCount,
    {
      id: 'eco-brackets',
      title: '免斜切省料方案',
      tagline: '0 根斜型材 · 外置三角连接板直装',
      braceMode: 'none',
      maxBraces: 0,
      targetSwayMm: Math.max(options.maxSwayMm * 1.4, 3.0),
      targetDeflectionMm: Math.max(options.maxDeflectionMm * 1.35, 2.5),
      targetSF: Math.max(1.8, options.targetSafetyFactor * 0.85),
      recommendedJointType: options.jointType === 'rigid' ? 'rigid' : 'gusset-plate',
      preferFewerBrackets: true,
      allowPruneUnlockedBraces: true,
    },
    options,
  );

  const balancedScheme = buildSchemeVariant(
    completedBase,
    autoGeneratedCount,
    {
      id: 'balanced',
      title: '45°角撑均衡方案',
      tagline: '角落45°斜切短角撑 · 兼顾稳固与空间',
      braceMode: 'knee-45',
      maxBraces: 4,
      targetSwayMm: Math.max(1.5, options.maxSwayMm),
      targetDeflectionMm: Math.max(1.2, options.maxDeflectionMm),
      targetSF: options.targetSafetyFactor,
      recommendedJointType:
        options.jointType === 'pinned' || options.jointType === 'builtin'
          ? 'semi-rigid'
          : options.jointType,
      preferFewerBrackets: false,
      allowPruneUnlockedBraces: false,
    },
    options,
  );

  const rigidScheme = buildSchemeVariant(
    completedBase,
    autoGeneratedCount,
    {
      id: 'ultra-rigid',
      title: '满跨斜撑高刚方案',
      tagline: '90°平切满跨斜撑+万向铰链 · 极致防晃',
      braceMode: 'full-bay',
      maxBraces: 4,
      targetSwayMm: Math.min(0.9, options.maxSwayMm * 0.6),
      targetDeflectionMm: Math.min(0.8, options.maxDeflectionMm * 0.65),
      targetSF: Math.max(3.5, options.targetSafetyFactor + 1.0),
      recommendedJointType:
        options.jointType === 'rigid' ? 'rigid' : 'gusset-plate',
      preferFewerBrackets: false,
      allowPruneUnlockedBraces: false,
    },
    options,
  );

  const candidates = [balancedScheme, ecoScheme, rigidScheme];

  // Multi-objective weighted scoring (0..100) using user weights for Material / Stability / Brackets
  const wMat = Math.max(0.5, options.weights.material);
  const wStab = Math.max(0.5, options.weights.stability);
  const wBrk = Math.max(0.5, options.weights.brackets);
  const wSum = wMat + wStab + wBrk;

  const minCost = Math.max(1, Math.min(...candidates.map((c) => c.totalCostCNY)));
  const minBrackets = Math.max(1, Math.min(...candidates.map((c) => c.bracketCount)));

  for (const c of candidates) {
    // 1. Material & Cost score (0..100)
    const matScore = Math.max(35, Math.min(100, (minCost / Math.max(1, c.totalCostCNY)) * 100));

    // 2. Stability score (0..100): rewards sway <= target, high SF, and no slip risk
    const swayRatio = c.maxSwayMm / Math.max(0.5, options.maxSwayMm);
    const swayScore = swayRatio <= 1 ? 100 - swayRatio * 12 : Math.max(20, 88 / swayRatio);
    const sfScore = Math.min(100, (c.minSafetyFactor / Math.max(1.5, options.targetSafetyFactor)) * 85);
    const slipPenalty = c.fea.jointSlipRisk ? 25 : 0;
    const stabScore = Math.max(15, Math.min(100, 0.65 * swayScore + 0.35 * sfScore - slipPenalty));

    // 3. Corner bracket simplicity score (0..100)
    const brkScore = Math.max(
      40,
      Math.min(100, (minBrackets / Math.max(1, c.bracketCount)) * 100),
    );

    c.score = Math.round((wMat * matScore + wStab * stabScore + wBrk * brkScore) / wSum);
  }

  candidates.sort((a, b) => b.score - a.score);

  return {
    beforeModel,
    beforeFea,
    beforeBracketCount: beforeHw.bracketCount,
    beforeTotalCostCNY,
    lockedMemberIds,
    candidates,
    recommendedId: candidates[0].id,
  };
}
